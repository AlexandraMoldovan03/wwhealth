"""
Exports built ONLY from data the caller may already read (own data, or the sections a patient granted a doctor):
  • emergency_summary: FHIR R4 document Bundle, IPS-inspired (Composition + allergies / problems / medication /
    results / procedures). Only CONFIRMED items; suspicions and items needing confirmation are left out and counted.
    Not claimed IPS-conformant (not validated against the IPS profile).
  • labs_csv: full confirmed lab history (name, value, unit, reference range, interpretation, date, source).
  • summary_pdf: structured medical PDF (same prioritised data as the Emergency Passport + lab history).
  • archive_zip: FHIR bundle + emergency summary + CSV + PDF + the original files the caller may read + manifest.
"""
import csv
import html
import io
import json
import re
import uuid
import zipfile
from collections.abc import Callable
from datetime import UTC, datetime

from app.schemas.emergency_passport import PassportItem, PrioritizedPassport
from app.services import fhir_service
from app.services.clinical_rules import lab_status
from app.services.emergency_passport import build_passport, profile_dict

LOINC = "http://loinc.org"
MAX_ZIP_DOCUMENTS = 50
MAX_ZIP_BYTES = 100 * 1024 * 1024
DISCLAIMER_EN = ("Generated by WWHealth from data confirmed by the patient. Not a diagnosis and not an official "
                 "medical record; items needing confirmation are excluded.")

# ─────────────────────────────────────────────────────────── IPS-inspired emergency summary

SECTIONS = (  # (key, LOINC code, display, title, required)
    ("allergies", "48765-2", "Allergies and adverse reactions Document", "Allergies and intolerances", True),
    ("problems", "11450-4", "Problem list - Reported", "Active problems", True),
    ("medications", "10160-0", "History of Medication use Narrative", "Medication summary", True),
    ("results", "30954-2", "Relevant diagnostic tests/laboratory data Narrative", "Results (abnormal / critical)", False),
    ("procedures", "47519-4", "History of Procedures Document", "History of procedures", False),
    ("past", "11348-0", "History of Past illness Narrative", "Past illnesses", False),
)
CLINICAL = "http://terminology.hl7.org/CodeSystem/"


def _cc(system: str, code: str) -> dict:
    return {"coding": [{"system": CLINICAL + system, "code": code}]}


def _div(lines: list[str]) -> str:
    items = "".join(f"<li>{html.escape(x)}</li>" for x in lines) if lines else ""
    return f'<div xmlns="http://www.w3.org/1999/xhtml">{"<ul>" + items + "</ul>" if items else ""}</div>'


def _note(item: PassportItem) -> list[dict]:
    notes = []
    if item.conflict:
        notes.append({"text": "Conflicting sources: " + " / ".join(item.conflict_values or ["see sources"])})
    docs = [s.document_title for s in item.sources if s.kind != "profile" and s.document_title]
    if docs:
        notes.append({"text": "Source: " + "; ".join(dict.fromkeys(docs))})
    return notes


def _include(item: PassportItem) -> bool:
    return item.confirmed and "suspected" not in item.flags


def emergency_summary(patient_id: str, record, labs: list[dict] | None, facts: list[dict] | None,
                      passport: PrioritizedPassport | None = None) -> dict:
    passport = passport or build_passport(profile_dict(record), facts=facts, labs=labs or [])
    pid = fhir_service._safe(patient_id)
    subject = {"reference": f"Patient/{pid}"}
    patient: dict = {"resourceType": "Patient", "id": pid, "identifier": [fhir_service._id("patient", patient_id)]}
    if record is not None:
        if record.full_name:
            patient["name"] = [{"text": record.full_name}]
        if record.date_of_birth:
            patient["birthDate"] = record.date_of_birth[:10]
        if record.sex:
            patient["gender"] = record.sex

    resources: list[dict] = []
    section_items: dict[str, list[tuple[str, str]]] = {k: [] for k, *_ in SECTIONS}
    excluded = 0
    items = [*passport.critical, *passport.essential, *passport.investigations]
    for n, item in enumerate(items):
        if not _include(item):
            excluded += 1
            continue
        rid = fhir_service._safe(f"ips-{n}-{re.sub(r'[^a-z0-9]', '', item.key.lower())[:30]}")
        res: dict | None = None
        if item.kind == "allergy":
            res = {"resourceType": "AllergyIntolerance", "id": rid, "patient": subject, "code": {"text": item.label},
                   "clinicalStatus": _cc("allergyintolerance-clinical", "active"),
                   "verificationStatus": _cc("allergyintolerance-verification", "confirmed")}
            if item.severity == "severe" or "anaphylaxis" in item.flags:
                res["criticality"] = "high"
            if item.detail:
                res["reaction"] = [{"manifestation": [{"text": item.detail}],
                                    **({"severity": item.severity} if item.severity else {})}]
            key, line = "allergies", " — ".join(x for x in (item.label, item.detail, item.severity) if x)
        elif item.kind == "condition":
            res = {"resourceType": "Condition", "id": rid, "subject": subject, "code": {"text": item.label},
                   "clinicalStatus": _cc("condition-clinical", "active"),
                   "verificationStatus": _cc("condition-ver-status", "confirmed")}
            key, line = "problems", item.label
        elif item.kind == "history":
            res = {"resourceType": "Condition", "id": rid, "subject": subject, "code": {"text": item.label},
                   "clinicalStatus": _cc("condition-clinical", "resolved"),
                   "verificationStatus": _cc("condition-ver-status", "confirmed")}
            key, line = "past", item.label
        elif item.kind == "medication":
            res = {"resourceType": "MedicationStatement", "id": rid, "subject": subject, "status": "active",
                   "medicationCodeableConcept": {"text": item.label}}
            if item.detail:
                res["dosage"] = [{"text": item.detail}]
            key, line = "medications", " — ".join(x for x in (item.label, item.detail) if x)
        elif item.kind == "procedure":
            res = {"resourceType": "Procedure", "id": rid, "subject": subject, "status": "completed",
                   "code": {"text": item.label}}
            key, line = "procedures", " — ".join(x for x in (item.label, item.detail) if x)
        elif item.kind == "lab" and item.lab:
            src = item.sources[0] if item.sources else None
            res = fhir_service.observation({"name": item.label, "value": item.lab.value, "unit": item.lab.unit,
                                            "reference_range": item.lab.reference_range, "measured_at": item.lab.date,
                                            "document_id": src.document_id if src else None}, subject, None, n)
            res["id"] = rid
            key = "results"
            line = f"{item.label}: {item.lab.value} {item.lab.unit or ''}".strip() + (
                f" (ref. {item.lab.reference_range})" if item.lab.reference_range else "") + (" — CRITICAL" if item.lab.critical else "")
        elif item.kind == "blood_type":
            res = {"resourceType": "Observation", "id": rid, "status": "final", "subject": subject,
                   "code": {"coding": [{"system": LOINC, "code": "882-1", "display": "ABO and Rh group [Type] in Blood"}]},
                   "valueCodeableConcept": {"text": item.label}, "note": [{"text": "Reported by the patient."}]}
            key, line = "results", f"Blood group (reported by the patient): {item.label}"
        if res is None:
            continue
        notes = _note(item)
        if notes and res["resourceType"] != "Observation":
            res["note"] = [*res.get("note", []), *notes]
        resources.append(res)
        section_items[key].append((f"{res['resourceType']}/{res['id']}", line + (" [conflicting sources]" if item.conflict else "")))

    sections = []
    for key, code, display, title, required in SECTIONS:
        rows = section_items[key]
        if not rows and not required:
            continue
        section: dict = {"title": title, "code": {"coding": [{"system": LOINC, "code": code, "display": display}]}}
        if rows:
            section["text"] = {"status": "generated", "div": _div([line for _, line in rows])}
            section["entry"] = [{"reference": ref} for ref, _ in rows]
        else:
            empty = "Allergies unknown — no allergy information recorded." if key == "allergies" else "No information recorded."
            section["text"] = {"status": "generated", "div": _div([empty])}
            section["emptyReason"] = _cc("list-empty-reason", "unavailable")
        sections.append(section)

    now = datetime.now(UTC).isoformat()
    composition = {
        "resourceType": "Composition", "id": "emergency-summary", "status": "final",
        "type": {"coding": [{"system": LOINC, "code": "60591-5", "display": "Patient summary Document"}]},
        "subject": subject, "date": now, "author": [{"display": "WWHealth (generated from patient-confirmed data)"}],
        "title": "Emergency summary (IPS-inspired; not validated against the IPS profile)",
        "section": sections,
        "text": {"status": "generated", "div": _div([DISCLAIMER_EN] + (
            [f"{excluded} item(s) needing confirmation or marked as suspected were not included."] if excluded else []))},
    }
    bundle = {"resourceType": "Bundle", "type": "document", "timestamp": now,
              "identifier": {"system": "urn:wwhealth:emergency-summary", "value": str(uuid.uuid4())},
              "entry": [fhir_service._entry(r) for r in (composition, patient, *resources)]}
    return fhir_service.validate(fhir_service.finalize(bundle))


# ─────────────────────────────────────────────────────────── CSV

CSV_HEADER = ["analiza", "valoare", "unitate", "interval_referinta", "interpretare", "data", "sursa", "document_id"]
INTERP = {"high": "H", "low": "L", "normal": "N", "unknown": ""}


def _cell(value: object) -> str:
    text = "" if value is None else str(value)
    # spreadsheet formula injection: =, +, @, tab, CR, or "-" not followed by a number
    if text and (text[0] in "=+@\t\r" or (text[0] == "-" and not re.match(r"-\d", text))):
        return "'" + text
    return text


def labs_csv(labs: list[dict] | None) -> str:
    rows = sorted((r for r in labs or [] if r.get("name") and r.get("value") not in (None, "")),
                  key=lambda r: (str(r["name"]).lower(), str(r.get("measured_at") or r.get("document_date") or "")), reverse=False)
    out = io.StringIO()
    writer = csv.writer(out, lineterminator="\r\n")
    writer.writerow(CSV_HEADER)
    for r in rows:
        writer.writerow([_cell(x) for x in (
            r["name"], r["value"], r.get("unit"), r.get("reference_range"),
            INTERP[lab_status(str(r["value"]), r.get("reference_range"))],
            str(r.get("measured_at") or r.get("document_date") or "")[:10], r.get("document_title"), r.get("document_id"))])
    return "﻿" + out.getvalue()  # BOM: Excel opens UTF-8 (diacritics) correctly


# ─────────────────────────────────────────────────────────── PDF

_TRANSLIT = str.maketrans({"ă": "a", "Ă": "A", "ș": "s", "ş": "s", "Ș": "S", "Ş": "S", "ț": "t", "ţ": "t", "Ț": "T",
                           "Ţ": "T", "–": "-", "—": "-", "„": '"', "”": '"', "“": '"', "’": "'", "↑": "^", "↓": "v",
                           "≤": "<=", "≥": ">=", "µ": "u", "μ": "u"})


def _latin(text: object) -> str:
    return str(text or "").translate(_TRANSLIT).encode("latin-1", "replace").decode("latin-1")


PDF_GROUPS = {"allergy": "Alergii", "condition": "Afectiuni", "medication": "Medicatie", "lab": "Analize",
              "blood_type": "Grupa sanguina", "history": "Antecedente", "procedure": "Interventii chirurgicale"}


def summary_pdf(record, passport: PrioritizedPassport, labs: list[dict] | None) -> bytes:
    from fpdf import FPDF
    from fpdf.enums import XPos, YPos

    pdf = FPDF(format="A4")
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()
    nl = {"new_x": XPos.LMARGIN, "new_y": YPos.NEXT}
    width = pdf.w - pdf.l_margin - pdf.r_margin

    def heading(text: str, size: int = 13) -> None:
        pdf.ln(2)
        pdf.set_font("Helvetica", "B", size)
        pdf.multi_cell(width, 7, _latin(text), **nl)
        pdf.set_font("Helvetica", "", 10)

    def line(text: str, bold: bool = False) -> None:
        pdf.set_font("Helvetica", "B" if bold else "", 10)
        pdf.multi_cell(width, 5, _latin(text), **nl)

    heading("WWHealth - Rezumat medical structurat", 16)
    line(f"Generat: {datetime.now(UTC).strftime('%Y-%m-%d %H:%M')} UTC")
    if record is not None:
        line(" · ".join(x for x in (record.full_name, f"Data nasterii: {record.date_of_birth}" if record.date_of_birth else None) if x))
    line("Generat din date confirmate de pacient. Nu este un diagnostic si nu inlocuieste documentele medicale oficiale.")

    def items(title: str, entries: list[PassportItem], unknown_allergies: bool = False) -> None:
        heading(title)
        if unknown_allergies:
            line("Alergii: ALERGII NECUNOSCUTE (nicio informatie inregistrata)", bold=True)
        if not entries and not unknown_allergies:
            line("Nicio informatie.")
        for kind, label in PDF_GROUPS.items():
            group = [i for i in entries if i.kind == kind]
            if not group:
                continue
            line(label + ":", bold=True)
            for i in group:
                text = i.label
                if i.lab:
                    text += f": {i.lab.value} {i.lab.unit or ''}".rstrip() + (f" (ref. {i.lab.reference_range})" if i.lab.reference_range else "")
                    text += " - VALOARE CRITICA" if i.lab.critical else ""
                if i.detail:
                    text += f" - {i.detail}"
                if i.severity:
                    text += f" [{i.severity}]"
                if not i.confirmed:
                    text += " [NECESITA CONFIRMARE]"
                if i.conflict:
                    text += " [SURSE CONTRADICTORII: " + " / ".join(i.conflict_values) + "]"
                line("  - " + text)

    items("P1 - Critic pentru urgenta", passport.critical, passport.allergies_status == "unknown")
    items("P2 - Informatii esentiale", passport.essential)
    if passport.investigations:
        items("P3 - Rezultate anormale", passport.investigations)

    rows = sorted((r for r in labs or [] if r.get("name")), key=lambda r: (str(r["name"]).lower(),
                                                                         str(r.get("measured_at") or r.get("document_date") or "")))
    if rows:
        heading("Istoric analize")
        cols = [("Analiza", 0.28), ("Valoare", 0.16), ("Referinta", 0.18), ("", 0.05), ("Data", 0.13), ("Sursa", 0.20)]
        pdf.set_font("Helvetica", "B", 9)
        for name, w in cols:
            pdf.cell(width * w, 6, _latin(name), border=1)
        pdf.ln()
        pdf.set_font("Helvetica", "", 8)
        for r in rows:
            values = [r["name"], f"{r['value']} {r.get('unit') or ''}".strip(), r.get("reference_range") or "",
                      INTERP[lab_status(str(r["value"]), r.get("reference_range"))],
                      str(r.get("measured_at") or r.get("document_date") or "")[:10], r.get("document_title") or ""]
            for (_, w), v in zip(cols, values, strict=True):
                text = _latin(v)
                while text and pdf.get_string_width(text) > width * w - 1.5:
                    text = text[:-1]
                pdf.cell(width * w, 5, text, border=1)
            pdf.ln()
    return bytes(pdf.output())


# ─────────────────────────────────────────────────────────── ZIP

def _safe_name(text: str, fallback: str) -> str:
    name = re.sub(r"[^A-Za-z0-9._-]+", "_", _latin(text)).strip("._")[:60]
    return name or fallback


def archive_zip(fhir_bundle: dict, summary: dict, csv_text: str, pdf: bytes, documents: list | None,
                fetch: Callable[[str], tuple[bytes, str, str] | None] | None) -> bytes:
    """documents=None → the caller may not read documents (manifest says so); never fetched then."""
    buf = io.BytesIO()
    manifest: dict = {"generated_at": datetime.now(UTC).isoformat(), "fhir_version": "4.0.1",
                      "note": DISCLAIMER_EN, "documents": [], "documents_not_included": []}
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("fhir/bundle.json", json.dumps(fhir_bundle, ensure_ascii=False, indent=2))
        zf.writestr("fhir/emergency-summary.json", json.dumps(summary, ensure_ascii=False, indent=2))
        zf.writestr("labs.csv", csv_text)
        zf.writestr("summary.pdf", pdf)
        if documents is None:
            manifest["documents_not_included"].append({"reason": "not_shared"})
        total = 0
        used: set[str] = set()
        for n, doc in enumerate(documents or []):
            if n >= MAX_ZIP_DOCUMENTS:
                manifest["documents_not_included"].append({"document_id": doc.id, "reason": "limit"})
                continue
            found = fetch(doc.id) if fetch and doc.file_url else None
            if not found:
                manifest["documents_not_included"].append({"document_id": doc.id, "reason": "no_file"})
                continue
            content, mime, filename = found
            if total + len(content) > MAX_ZIP_BYTES:
                manifest["documents_not_included"].append({"document_id": doc.id, "reason": "size_limit"})
                continue
            total += len(content)
            ext = filename.rsplit(".", 1)[-1].lower() if "." in filename else "bin"
            base = _safe_name(doc.title, f"document-{n + 1}")
            path = f"documents/{base}.{ext}"
            if path in used:
                path = f"documents/{base}-{n + 1}.{ext}"
            used.add(path)
            zf.writestr(path, content)
            manifest["documents"].append({"document_id": doc.id, "title": doc.title, "path": path, "mime_type": mime,
                                          "fhir_document_reference": f"DocumentReference/{fhir_service._safe('doc-' + doc.id)}"})
        zf.writestr("manifest.json", json.dumps(manifest, ensure_ascii=False, indent=2))
    return buf.getvalue()
