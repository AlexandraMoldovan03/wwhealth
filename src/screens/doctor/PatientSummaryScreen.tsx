import { router, Stack } from 'expo-router';
import { StyleSheet, View } from 'react-native';

import { AppButton, AppCard, AppText, Badge, DemoNotice, ErrorState, ScreenContainer, SectionHeader } from '@/components/ui';
import { spacing } from '@/constants/theme';
import { NoAccessState } from '@/features/doctor/components/NoAccessState';
import { useDoctorPatient } from '@/features/doctor/useDoctorPatient';
import { MedicalEventList } from '@/features/history/components/MedicalEventList';
import { ProfileSections } from '@/features/patient/components/ProfileSections';
import { useSubmit } from '@/hooks/useSubmit';
import { useTheme } from '@/hooks/useTheme';
import { api } from '@/services/backend';
import { formatDateTime } from '@/utils/format';

/** Patient Summary (doctor view) + medical summary, optionally read aloud (ElevenLabs). */
export function PatientSummaryScreen() {
  const { colors } = useTheme();
  const { session, patient } = useDoctorPatient();
  const voice = useSubmit(api.voiceSummary);

  if (!session || !patient) return <ScreenContainer edges={['bottom']}><NoAccessState /></ScreenContainer>;

  return (
    <ScreenContainer edges={['bottom']}>
      <Stack.Screen options={{ title: patient.fullName }} />
      <AppCard style={styles.access}>
        <AppText variant="caption" color="textMuted">
          Access until {formatDateTime(session.expiresAt)}
        </AppText>
        <View style={styles.badges}>
          {session.scopes.map((s) => (
            <Badge key={s} label={s} color={colors.primary} />
          ))}
        </View>
      </AppCard>

      <View style={styles.actions}>
        <View style={styles.flex}>
          <AppButton title="Documents" icon="folder-open-outline" variant="outline" fullWidth
            onPress={() => router.push({ pathname: '/doctor/patient/[id]/documents', params: { id: patient.id } })} />
        </View>
        <View style={styles.flex}>
          <AppButton title="LungVision" icon="scan-outline" variant="outline" fullWidth
            onPress={() => router.push({ pathname: '/doctor/patient/[id]/lungvision', params: { id: patient.id } })} />
        </View>
      </View>

      <View style={styles.section}>
        <SectionHeader title="Medical summary" subtitle="Generated by backend (Gemini) · audio via ElevenLabs" />
        <AppButton
          title={voice.data ? 'Regenerate summary' : 'Generate summary'}
          icon="volume-high-outline"
          variant="secondary"
          loading={voice.isLoading}
          onPress={() => void voice.run({ patientId: patient.id, language: 'en' })}
        />
        {voice.error && <ErrorState message={voice.error} />}
        {voice.data && (
          <AppCard style={styles.section}>
            <AppText>{voice.data.text}</AppText>
            {/* TODO(mobile): play voice.data.audioUrl with expo-audio when the backend returns it. */}
            <AppText variant="caption" color="textMuted">
              {voice.data.audioUrl ? 'Audio ready' : 'Audio not available yet'}
            </AppText>
            {voice.data.isDemo && <DemoNotice message="DEMO — summary generated from mock data, no audio." />}
          </AppCard>
        )}
      </View>

      <ProfileSections profile={patient} />

      <View style={styles.section}>
        <SectionHeader title="Recent history" />
        {session.scopes.includes('history') ? (
          <MedicalEventList events={patient.history.slice(0, 5)} />
        ) : (
          <ErrorState title="Not shared" message="The patient did not share their history." />
        )}
      </View>
    </ScreenContainer>
  );
}

const styles = StyleSheet.create({
  access: { gap: spacing.sm },
  badges: { flexDirection: 'row', flexWrap: 'wrap', gap: spacing.xs },
  actions: { flexDirection: 'row', gap: spacing.md },
  flex: { flex: 1 },
  section: { gap: spacing.sm },
});
