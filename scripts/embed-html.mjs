import { mkdir, readFile, writeFile } from 'node:fs/promises';

const output = new URL('../frontend/design-system/html/', import.meta.url);
await mkdir(output, { recursive: true });

for (const name of ['medical-passport-button']) {
  const source = new URL(`../assets/html/${name}.html`, import.meta.url);
  const html = await readFile(source, 'utf8');
  const embedded = html.replace('<head>', '<head><script>window.__EMBEDDED=true</script>');
  await writeFile(new URL(`${name}.ts`, output), `// Generated by npm run embed:html.\nexport default ${JSON.stringify(embedded)};\n`);
}
